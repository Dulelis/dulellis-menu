-- Reservas temporarias impedem que carrinhos abandonados prendam estoque para sempre.
create table if not exists public.reservas_estoque (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null references public.clientes(id) on delete cascade,
  produto_id bigint not null references public.estoque(id) on delete cascade,
  quantidade integer not null,
  expires_at timestamptz not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reservas_estoque_quantidade_check check (quantidade > 0),
  constraint reservas_estoque_cliente_produto_unique unique (cliente_id, produto_id)
);

create index if not exists idx_reservas_estoque_expiracao
  on public.reservas_estoque(expires_at);

create or replace function public.liberar_reservas_estoque_expiradas()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  total_liberado integer := 0;
begin
  with expiradas as (
    delete from public.reservas_estoque
    where expires_at <= now()
    returning produto_id, quantidade
  ), somas as (
    select produto_id, sum(quantidade)::integer as quantidade
    from expiradas
    group by produto_id
  ), atualizadas as (
    update public.estoque e
    set quantidade = coalesce(e.quantidade, 0) + s.quantidade
    from somas s
    where e.id = s.produto_id
    returning s.quantidade
  )
  select coalesce(sum(quantidade), 0)::integer
  into total_liberado
  from atualizadas;

  return total_liberado;
end;
$$;

create or replace function public.ajustar_reserva_estoque(
  p_cliente_id bigint,
  p_produto_id bigint,
  p_delta integer
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  estoque_atual integer;
  reserva_atual integer;
  quantidade_movimento integer;
  novo_estoque integer;
begin
  if p_cliente_id is null or p_cliente_id <= 0
    or p_produto_id is null or p_produto_id <= 0
    or p_delta = 0 or abs(p_delta) > 50 then
    raise exception 'Parametros de reserva invalidos.' using errcode = '22023';
  end if;

  perform public.liberar_reservas_estoque_expiradas();

  select quantidade
  into estoque_atual
  from public.estoque
  where id = p_produto_id
  for update;

  if not found then
    return jsonb_build_object('updated', false, 'reason', 'not_found');
  end if;

  if p_delta < 0 then
    quantidade_movimento := abs(p_delta);
    if coalesce(estoque_atual, 0) < quantidade_movimento then
      return jsonb_build_object('updated', false, 'reason', 'insufficient');
    end if;

    novo_estoque := estoque_atual - quantidade_movimento;
    update public.estoque
    set quantidade = novo_estoque
    where id = p_produto_id;

    insert into public.reservas_estoque (
      cliente_id,
      produto_id,
      quantidade,
      expires_at,
      updated_at
    ) values (
      p_cliente_id,
      p_produto_id,
      quantidade_movimento,
      now() + interval '30 minutes',
      now()
    )
    on conflict (cliente_id, produto_id)
    do update set
      quantidade = public.reservas_estoque.quantidade + excluded.quantidade,
      expires_at = excluded.expires_at,
      updated_at = now();

    return jsonb_build_object(
      'updated', true,
      'quantidade', novo_estoque,
      'reserved', quantidade_movimento
    );
  end if;

  select quantidade
  into reserva_atual
  from public.reservas_estoque
  where cliente_id = p_cliente_id and produto_id = p_produto_id
  for update;

  if not found then
    return jsonb_build_object(
      'updated', true,
      'quantidade', estoque_atual,
      'released', 0,
      'reason', 'no_reservation'
    );
  end if;

  quantidade_movimento := least(p_delta, reserva_atual);
  novo_estoque := estoque_atual + quantidade_movimento;
  update public.estoque
  set quantidade = novo_estoque
  where id = p_produto_id;

  if quantidade_movimento >= reserva_atual then
    delete from public.reservas_estoque
    where cliente_id = p_cliente_id and produto_id = p_produto_id;
  else
    update public.reservas_estoque
    set
      quantidade = quantidade - quantidade_movimento,
      expires_at = now() + interval '30 minutes',
      updated_at = now()
    where cliente_id = p_cliente_id and produto_id = p_produto_id;
  end if;

  return jsonb_build_object(
    'updated', true,
    'quantidade', novo_estoque,
    'released', quantidade_movimento
  );
end;
$$;

create or replace function public.consumir_reservas_estoque(
  p_cliente_id bigint,
  p_itens jsonb
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  item jsonb;
  produto bigint;
  quantidade_pedida integer;
  quantidade_reservada integer;
begin
  if p_cliente_id is null or p_cliente_id <= 0
    or p_itens is null or jsonb_typeof(p_itens) <> 'array'
    or jsonb_array_length(p_itens) = 0 then
    raise exception 'Reserva do pedido invalida.' using errcode = '22023';
  end if;

  for item in select value from jsonb_array_elements(p_itens)
  loop
    produto := (item->>'id')::bigint;
    quantidade_pedida := (item->>'qtd')::integer;
    if produto <= 0 or quantidade_pedida <= 0 then
      raise exception 'Item de reserva invalido.' using errcode = '22023';
    end if;

    select quantidade
    into quantidade_reservada
    from public.reservas_estoque
    where cliente_id = p_cliente_id
      and produto_id = produto
      and expires_at > now()
    for update;

    if not found or quantidade_reservada < quantidade_pedida then
      raise exception 'Reserva de estoque insuficiente para o produto %.', produto
        using errcode = 'P0001';
    end if;

    if quantidade_reservada = quantidade_pedida then
      delete from public.reservas_estoque
      where cliente_id = p_cliente_id and produto_id = produto;
    else
      update public.reservas_estoque
      set
        quantidade = quantidade - quantidade_pedida,
        updated_at = now()
      where cliente_id = p_cliente_id and produto_id = produto;
    end if;
  end loop;

  return true;
end;
$$;

