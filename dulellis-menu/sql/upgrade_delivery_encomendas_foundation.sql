-- A validacao final da agenda acontece no banco para impedir duas reservas
-- simultaneas de ultrapassarem a capacidade do mesmo horario.
create or replace function public.validar_agendamento_encomenda()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  config public.configuracoes_encomendas%rowtype;
  horario_local timestamp;
  data_local date;
  hora_local time;
  dia_semana text;
  capacidade_slot integer;
  pedidos_no_slot integer;
begin
  if new.tipo_pedido <> 'encomenda' then
    return new;
  end if;

  -- Alteracoes comuns de producao/pagamento nao precisam revalidar a agenda.
  -- Ao cancelar, sempre permitimos a liberacao da vaga; ao reativar uma
  -- encomenda cancelada, a capacidade volta a ser conferida abaixo.
  if tg_op = 'UPDATE'
    and new.tipo_pedido is not distinct from old.tipo_pedido
    and new.agendado_para is not distinct from old.agendado_para
  then
    if lower(coalesce(new.status_pedido, '')) in ('cancelado', 'cancelada', 'recusado')
      or lower(coalesce(new.status_producao, '')) = 'cancelada'
      or (
        lower(coalesce(old.status_pedido, '')) not in ('cancelado', 'cancelada', 'recusado')
        and lower(coalesce(old.status_producao, '')) <> 'cancelada'
      )
    then
      return new;
    end if;
  end if;

  select * into config
  from public.configuracoes_encomendas
  order by id
  limit 1;

  if not found or config.ativo = false then
    raise exception 'As encomendas estao fechadas no momento.' using errcode = 'P0001';
  end if;
  if new.agendado_para is null then
    raise exception 'Informe a data e o horario da encomenda.' using errcode = '23514';
  end if;
  if new.agendado_para < now() + make_interval(hours => config.antecedencia_minima_horas) then
    raise exception 'A encomenda nao respeita a antecedencia minima.' using errcode = 'P0001';
  end if;
  if new.agendado_para > now() + make_interval(days => config.horizonte_maximo_dias) then
    raise exception 'A data da encomenda esta alem do periodo disponivel.' using errcode = 'P0001';
  end if;

  horario_local := new.agendado_para at time zone config.timezone;
  data_local := horario_local::date;
  hora_local := horario_local::time;
  dia_semana := (array['domingo','segunda','terca','quarta','quinta','sexta','sabado'])[
    extract(dow from horario_local)::integer + 1
  ];

  if not (dia_semana = any(config.dias_semana)) then
    raise exception 'Nao recebemos encomendas para esse dia da semana.' using errcode = 'P0001';
  end if;
  if hora_local < config.hora_inicio or hora_local >= config.hora_fim then
    raise exception 'Horario fora da agenda de encomendas.' using errcode = 'P0001';
  end if;
  if mod(
    (extract(epoch from (hora_local - config.hora_inicio)) / 60)::integer,
    config.intervalo_slot_minutos
  ) <> 0 then
    raise exception 'Escolha um horario valido da agenda de encomendas.' using errcode = 'P0001';
  end if;
  if exists (
    select 1
    from public.bloqueios_encomendas b
    where b.ativo = true
      and new.agendado_para >= b.inicio
      and new.agendado_para < b.fim
  ) then
    raise exception 'Esse horario esta bloqueado para encomendas.' using errcode = 'P0001';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended(to_char(new.agendado_para at time zone 'UTC', 'YYYY-MM-DD HH24:MI'), 0)
  );

  select c.capacidade_total
  into capacidade_slot
  from public.capacidade_encomendas c
  where c.ativo = true
    and c.data = data_local
    and hora_local >= c.hora_inicio
    and hora_local < c.hora_fim
  order by c.hora_inicio desc
  limit 1;

  capacidade_slot := coalesce(capacidade_slot, config.capacidade_padrao_por_slot);
  select count(*)::integer
  into pedidos_no_slot
  from public.pedidos p
  where p.tipo_pedido = 'encomenda'
    and p.agendado_para = new.agendado_para
    and p.id is distinct from new.id
    and lower(coalesce(p.status_pedido, '')) not in ('cancelado', 'cancelada', 'recusado');

  if capacidade_slot <= pedidos_no_slot then
    raise exception 'Esse horario acabou de atingir a capacidade maxima.' using errcode = 'P0001';
  end if;

  new.status_producao := coalesce(nullif(btrim(new.status_producao), ''), 'aguardando_confirmacao');
  return new;
end;
$$;

