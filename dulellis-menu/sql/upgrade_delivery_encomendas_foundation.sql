-- Converte a marcacao legada de retirada que ficava apenas na observacao.
-- Bancos mais antigos podem ainda nao ter a coluna observacao. O SQL dinamico
-- evita que o PostgreSQL tente resolver uma coluna inexistente ao ler o arquivo.
do $$
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'pedidos'
      and column_name = 'observacao'
  ) then
    execute $sql$
      update public.pedidos
      set tipo_recebimento = case
        when lower(coalesce(observacao, '')) like '%tipo de entrega: retirar no balcao%'
          then 'retirada'
        else 'entrega'
      end
      where tipo_recebimento is null or btrim(tipo_recebimento) = ''
    $sql$;
  else
    update public.pedidos
    set tipo_recebimento = 'entrega'
    where tipo_recebimento is null or btrim(tipo_recebimento) = '';
  end if;
end
$$;

