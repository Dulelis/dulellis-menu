-- Aplica sinal/saldo em uma unica transacao. O bloqueio da linha impede que
-- dois webhooks simultaneos sobrescrevam o saldo calculado pelo outro.
create or replace function public.registrar_pagamento_encomenda(
  p_pedido_id bigint,
  p_pagamento_id text,
  p_referencia text,
  p_tipo_pagamento text,
  p_valor_pago numeric,
  p_status text default 'approved',
  p_forma_pagamento text default 'Mercado Pago'
)
returns table (
  aplicado boolean,
  valor_sinal numeric,
  saldo_restante numeric,
  pagamento_completo boolean
)
language plpgsql
security definer
set search_path = public
as $$
declare
  pedido public.pedidos%rowtype;
  valor_aplicado numeric;
  novo_sinal numeric;
  novo_saldo numeric;
begin
  if nullif(btrim(coalesce(p_pagamento_id, '')), '') is null then
    raise exception 'Identificador do pagamento ausente.' using errcode = '22023';
  end if;
  if lower(coalesce(p_tipo_pagamento, '')) not in ('sinal', 'saldo', 'integral') then
    raise exception 'Tipo de pagamento da encomenda invalido.' using errcode = '22023';
  end if;

  select * into pedido
  from public.pedidos
  where id = p_pedido_id
  for update;

  if not found or pedido.tipo_pedido <> 'encomenda' then
    raise exception 'Encomenda nao encontrada.' using errcode = 'P0002';
  end if;

  if exists (
    select 1 from public.pedido_eventos e
    where e.tipo = 'pagamento_encomenda_aprovado'
      and e.dados->>'pagamento_id' = p_pagamento_id
  ) then
    return query select
      false,
      coalesce(pedido.valor_sinal, 0),
      coalesce(pedido.saldo_restante, greatest(coalesce(pedido.total, 0) - coalesce(pedido.valor_sinal, 0), 0)),
      coalesce(pedido.saldo_restante, 0) <= 0.009;
    return;
  end if;

  valor_aplicado := least(
    greatest(coalesce(pedido.saldo_restante, pedido.total - coalesce(pedido.valor_sinal, 0), 0), 0),
    greatest(coalesce(p_valor_pago, 0), 0)
  );
  if valor_aplicado <= 0 then
    raise exception 'Valor do pagamento invalido ou encomenda ja quitada.' using errcode = '22023';
  end if;

  novo_sinal := case
    when lower(p_tipo_pagamento) = 'sinal'
      then least(coalesce(pedido.total, 0), coalesce(pedido.valor_sinal, 0) + valor_aplicado)
    else coalesce(pedido.valor_sinal, 0)
  end;
  novo_saldo := greatest(
    coalesce(pedido.saldo_restante, pedido.total - coalesce(pedido.valor_sinal, 0), 0) - valor_aplicado,
    0
  );

  update public.pedidos
  set
    status_pagamento = case when novo_saldo <= 0.009 then 'approved' else 'partial' end,
    pagamento_id = p_pagamento_id,
    pagamento_referencia = nullif(btrim(coalesce(p_referencia, '')), ''),
    pagamento_atualizado_em = now(),
    forma_pagamento = coalesce(nullif(btrim(coalesce(p_forma_pagamento, '')), ''), forma_pagamento),
    valor_sinal = novo_sinal,
    saldo_restante = case when novo_saldo <= 0.009 then 0 else novo_saldo end
  where id = pedido.id;

  insert into public.pedido_eventos (pedido_id, tipo, descricao, dados, criado_por)
  values (
    pedido.id,
    'pagamento_encomenda_aprovado',
    case when novo_saldo <= 0.009
      then 'Pagamento integral da encomenda aprovado.'
      else 'Sinal da encomenda aprovado.'
    end,
    jsonb_build_object(
      'pagamento_id', p_pagamento_id,
      'referencia', p_referencia,
      'tipo_pagamento', lower(p_tipo_pagamento),
      'valor_pago', valor_aplicado,
      'saldo_restante', case when novo_saldo <= 0.009 then 0 else novo_saldo end,
      'status_origem', p_status
    ),
    'mercado_pago'
  );

  return query select
    true,
    novo_sinal,
    case when novo_saldo <= 0.009 then 0 else novo_saldo end,
    novo_saldo <= 0.009;
end;
$$;

